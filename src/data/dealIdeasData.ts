const CUSTOM_IDEAS_STORAGE_KEY = 'abdul_deals_custom_ideas_vault_v1';

/**
 * Get all ideas (Default curated list + Any custom ideas saved by Abdul Owner)
 */
export function getAllDealIdeas(): DealIdea[] {
  try {
    const raw = localStorage.getItem(CUSTOM_IDEAS_STORAGE_KEY);
    const custom: DealIdea[] = raw ? JSON.parse(raw) : [];
    return [...custom, ...DEAL_IDEAS_LIST];
  } catch (e) {
    console.error('Error loading custom ideas:', e);
    return DEAL_IDEAS_LIST;
  }
}

/**
 * Save a new custom idea created by Abdul Owner
 */
export function saveCustomDealIdea(idea: Omit<DealIdea, 'id'>): DealIdea {
  const newIdea: DealIdea = {
    ...idea,
    id: `custom-idea-${Date.now()}-${Math.random().toString(36).substring(2, 6)}`,
    isCustom: true,
  };

  try {
    const raw = localStorage.getItem(CUSTOM_IDEAS_STORAGE_KEY);
    const custom: DealIdea[] = raw ? JSON.parse(raw) : [];
    const updated = [newIdea, ...custom];
    localStorage.setItem(CUSTOM_IDEAS_STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Error saving custom idea:', e);
  }

  return newIdea;
}

/**
 * Delete a custom idea
 */
export function deleteCustomDealIdea(ideaId: string): DealIdea[] {
  try {
    const raw = localStorage.getItem(CUSTOM_IDEAS_STORAGE_KEY);
    const custom: DealIdea[] = raw ? JSON.parse(raw) : [];
    const updated = custom.filter((i) => i.id !== ideaId);
    localStorage.setItem(CUSTOM_IDEAS_STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {}
  return getAllDealIdeas();
}
